-- un registro de turno (o de tiempo sin programar) de una maquina
CREATE TABLE IF NOT EXISTS dwh.fact_produccion_turno (
    produccion_key bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fila_excel int NOT NULL,
    fecha_key int NOT NULL REFERENCES dwh.dim_fecha,
    maquina_key int NOT NULL REFERENCES dwh.dim_maquina,
    turno_key int NOT NULL REFERENCES dwh.dim_turno,
    referencia_key int NOT NULL REFERENCES dwh.dim_referencia,
    personal_key int NOT NULL REFERENCES dwh.dim_personal,
    tipo_registro text NOT NULL,
    horas_programadas numeric(6,2) NOT NULL CHECK (horas_programadas >= 0),
    pacas_producidas numeric(10,1) NOT NULL CHECK (pacas_producidas >= 0),
    horas_no_trabajadas numeric(6,2) NOT NULL CHECK (horas_no_trabajadas >= 0),
    tipo_no_trabajo_codigo smallint,
    tipo_no_trabajo text,
    horas_paro_turno numeric(12,6) NOT NULL,
    horas_paro_programado numeric(12,6) NOT NULL,
    horas_paro_calidad numeric(12,6) NOT NULL,
    horas_paro_disponibilidad numeric(12,6) NOT NULL,
    horas_programadas_netas numeric(12,6) NOT NULL,
    horas_operativas numeric(12,6) NOT NULL,
    meta_pacas_hora numeric(8,3) NOT NULL,
    pacas_ideales numeric(12,3) NOT NULL,
    es_atipico boolean NOT NULL DEFAULT false,
    sin_referencia boolean NOT NULL DEFAULT false,
    meta_estimada boolean NOT NULL DEFAULT false
);

-- un evento de paro: registro del Excel x codigo de paro
CREATE TABLE IF NOT EXISTS dwh.fact_paro (
    paro_evento_key bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fila_excel int NOT NULL,
    fecha_key int NOT NULL REFERENCES dwh.dim_fecha,
    maquina_key int NOT NULL REFERENCES dwh.dim_maquina,
    turno_key int NOT NULL REFERENCES dwh.dim_turno,
    referencia_key int NOT NULL REFERENCES dwh.dim_referencia,
    personal_key int NOT NULL REFERENCES dwh.dim_personal,
    paro_key int NOT NULL REFERENCES dwh.dim_paro,
    personal_involucrado_key int NOT NULL REFERENCES dwh.dim_personal,
    minutos_paro numeric(8,2) NOT NULL CHECK (minutos_paro > 0),
    horas_paro numeric(14,8) GENERATED ALWAYS AS (minutos_paro / 60.0) STORED
);
