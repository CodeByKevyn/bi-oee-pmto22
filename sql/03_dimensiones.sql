CREATE TABLE IF NOT EXISTS dwh.dim_fecha (
    fecha_key int PRIMARY KEY,
    fecha date NOT NULL UNIQUE,
    anio smallint NOT NULL,
    semestre smallint NOT NULL,
    trimestre smallint NOT NULL,
    mes smallint NOT NULL,
    nombre_mes text NOT NULL,
    anio_mes text NOT NULL,
    semana_iso smallint NOT NULL,
    dia_mes smallint NOT NULL,
    dia_semana smallint NOT NULL,
    nombre_dia text NOT NULL,
    es_fin_de_semana boolean NOT NULL
);

CREATE TABLE IF NOT EXISTS dwh.dim_maquina (
    maquina_key int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    maquina text NOT NULL UNIQUE,
    linea text NOT NULL,
    unidades_minuto numeric(6,1),
    factor_meta numeric(4,2)
);

CREATE TABLE IF NOT EXISTS dwh.dim_turno (
    turno_key int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    turno text NOT NULL UNIQUE,
    tipo_jornada text NOT NULL,
    hora_inicio time,
    hora_fin time,
    horas_nominales numeric(4,1),
    min_aseo smallint,
    min_pausa_activa smallint
);

-- scd tipo 2: si cambian las unidades por paca se cierra la version y se abre otra
CREATE TABLE IF NOT EXISTS dwh.dim_referencia (
    referencia_key int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    referencia text NOT NULL,
    marca text,
    tamano_cc int,
    colores smallint,
    display_por_paca int,
    unidades_por_paca int,
    en_maestro boolean NOT NULL DEFAULT true,
    vigente_desde date NOT NULL,
    vigente_hasta date NOT NULL DEFAULT '9999-12-31',
    es_vigente boolean NOT NULL DEFAULT true,
    UNIQUE (referencia, vigente_desde)
);

CREATE TABLE IF NOT EXISTS dwh.dim_personal (
    personal_key int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alias text NOT NULL UNIQUE,
    rol text NOT NULL
);

CREATE TABLE IF NOT EXISTS dwh.dim_paro (
    paro_key int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo smallint NOT NULL,
    nombre_codigo text NOT NULL,
    area_impacto text,
    subcodigo_nivel1 text NOT NULL DEFAULT 'Sin especificar',
    subcodigo_nivel2 text NOT NULL DEFAULT 'Sin especificar',
    clase_paro text NOT NULL CHECK (clase_paro IN ('programado', 'no programado')),
    tipo_perdida_oee text NOT NULL CHECK (tipo_perdida_oee IN ('disponibilidad', 'calidad', 'programado')),
    UNIQUE (codigo, subcodigo_nivel1, subcodigo_nivel2)
);

