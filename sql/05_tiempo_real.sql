-- lecturas hora a hora; las llena etl/simulador_hora.py
CREATE TABLE IF NOT EXISTS rt.lectura_hora (
    lectura_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts timestamptz NOT NULL,
    maquina text NOT NULL,
    turno text NOT NULL,
    referencia text,
    pacas numeric(8,2) NOT NULL CHECK (pacas >= 0),
    meta_pacas numeric(8,2) NOT NULL CHECK (meta_pacas >= 0),
    minutos_paro numeric(5,1) NOT NULL CHECK (minutos_paro BETWEEN 0 AND 60),
    codigo_paro smallint,
    escenario text NOT NULL DEFAULT 'normal',
    UNIQUE (maquina, ts)
);
